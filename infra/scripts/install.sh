#!/usr/bin/env bash
# One-command install of Basharnia Coach CRM on a fresh Ubuntu 24.04 VPS (run as root).
#
#   git clone https://github.com/Alinadaf01/GymApp.git /opt/basharnia
#   bash /opt/basharnia/infra/scripts/install.sh
#
# Asks a few questions, generates every secret itself, then: hardens the server,
# writes .env, builds the images, gets the SSL certificate, starts everything,
# creates the coach account, downloads the Whisper model and registers the
# Telegram webhook. Safe to run again: finished steps are skipped.
#
#   INSTALL_ENV_ONLY=1 ...   only write .env (used by tests)
#   Unattended: set DOMAIN, TELEGRAM_BOT_TOKEN, TELEGRAM_ALLOWED_USER_ID, ADMIN_USER,
#   LE_EMAIL and PANEL_USER in the environment; nothing is asked then.
set -euo pipefail

APP_DIR=$(cd "$(dirname "$0")/../.." && pwd)
ENV_FILE=${ENV_FILE:-$APP_DIR/.env}
cd "$APP_DIR"

say()  { printf '\n\033[1m== %s\033[0m\n' "$*"; }
ok()   { printf '✓ %s\n' "$*"; }
warn() { printf '! %s\n' "$*" >&2; }
die()  { printf '✗ %s\n' "$*" >&2; exit 1; }
rand() { openssl rand -base64 $(( ${1:-40} * 2 )) | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }
env_get() { grep -E "^$1=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- || true; }

ask() {  # ask VAR "question" [default] [secret]
  local var=$1 q=$2 def=${3:-} secret=${4:-} val=""
  if [[ -n ${!var:-} ]]; then return; fi   # already provided via environment
  while [[ -z $val ]]; do
    if [[ -n $secret ]]; then read -r -s -p "$q: " val; echo; else read -r -p "$q${def:+ [$def]}: " val; fi
    val=${val:-$def}
  done
  printf -v "$var" '%s' "$val"
}

write_env() {
  if [[ -f $ENV_FILE ]]; then ok ".env already exists — kept as is"; return; fi
  ask DOMAIN "Domain of the panel (e.g. coach.example.com)"
  ask TELEGRAM_BOT_TOKEN "Telegram bot token from @BotFather (hidden)" "" secret
  ask TELEGRAM_ALLOWED_USER_ID "The coach's numeric Telegram user id (from @userinfobot)"
  [[ $DOMAIN =~ ^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$ ]] || die "domain looks wrong: $DOMAIN"
  [[ $TELEGRAM_BOT_TOKEN =~ ^[0-9]+:[A-Za-z0-9_-]{30,}$ ]] || die "the bot token format looks wrong"
  [[ $TELEGRAM_ALLOWED_USER_ID =~ ^[0-9]{4,15}$ ]] || die "the Telegram user id must be a number (not @username)"
  local pg; pg=$(rand 32)
  umask 077
  cat > "$ENV_FILE" <<ENV
# Generated by infra/scripts/install.sh on $(date -u +%F). Keep this file private (chmod 600).
APP_ENV=production
APP_SECRET_KEY=$(rand 64)
DOMAIN=$DOMAIN
FRONTEND_URL=https://$DOMAIN
API_BASE_URL=https://$DOMAIN

POSTGRES_DB=basharnia
POSTGRES_USER=basharnia
POSTGRES_PASSWORD=$pg
DATABASE_URL=postgresql+psycopg://basharnia:$pg@db:5432/basharnia

TELEGRAM_BOT_TOKEN=$TELEGRAM_BOT_TOKEN
TELEGRAM_ALLOWED_USER_ID=$TELEGRAM_ALLOWED_USER_ID
TELEGRAM_WEBHOOK_SECRET=$(rand 48)

WHISPER_MODEL=small
WHISPER_DEVICE=cpu
WHISPER_COMPUTE_TYPE=int8
WHISPER_MODEL_DIR=/models
WHISPER_VOCAB_HINT=false
AUDIO_MAX_DURATION_SECONDS=900
# Voice test period: keep raw voices 30 days so they can be re-evaluated (0 = delete right away)
AUDIO_RETAIN_HOURS=${AUDIO_RETAIN_HOURS:-720}

STORAGE_ROOT=/data/basharnia
STORAGE_HOST_PATH=/data/basharnia
MAX_UPLOAD_MB=20
TIMEZONE=Asia/Tehran
ENV
  chmod 600 "$ENV_FILE"
  ok ".env written with freshly generated secrets"
}

if [[ ${INSTALL_ENV_ONLY:-0} == 1 ]]; then write_env; exit 0; fi

[[ $EUID -eq 0 ]] || die "run as root (sudo bash $0)"
grep -q 'VERSION_ID="24.04"' /etc/os-release || warn "tested on Ubuntu 24.04 only"

say "0/8 Network check (everything the install and the bot need)"
blocked=()
for url in https://api.telegram.org https://registry-1.docker.io/v2/ https://pypi.org/simple/ \
           https://registry.npmjs.org https://deb.debian.org/debian/ https://cdn.playwright.dev \
           https://huggingface.co https://acme-v02.api.letsencrypt.org/directory https://github.com; do
  code=$(curl -sS -m 15 -o /dev/null -w '%{http_code}' "$url" 2>/dev/null || true)
  if [[ -z $code || $code == 000 ]]; then blocked+=("$url"); else ok "reachable: $url"; fi
done
if [[ ${#blocked[@]} -gt 0 ]]; then
  printf '✗ not reachable from this server: %s\n' "${blocked[@]}" >&2
  if [[ " ${blocked[*]} " == *api.telegram.org* ]]; then
    die "Telegram is not reachable. The bot cannot work on this server (servers inside Iran cannot reach Telegram). Use a VPS outside Iran."
  fi
  die "Some required sites are blocked from this server; installation cannot continue."
fi

say "1/8 Questions"
ask ADMIN_USER "Linux user for logging in from now on (created if missing)" "coachadmin"
ask LE_EMAIL "Email for SSL certificate notices"
if [[ ! -f $ENV_FILE ]]; then write_env; fi
DOMAIN=$(env_get DOMAIN)

say "2/8 Server hardening and packages"
ADMIN_USER=$ADMIN_USER bash infra/scripts/setup-vps.sh
# The admin user runs `docker compose` from now on (member of the docker group),
# so it must own the checkout and be able to read .env (mode 600).
chown -R "$ADMIN_USER:$ADMIN_USER" "$APP_DIR"
git config --system --add safe.directory "$APP_DIR"

say "3/8 Checking that $DOMAIN points to this server"
public_ip=$(curl -fsS -4 -m 10 https://api.ipify.org || true)
dns_ip=$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}' || true)
if [[ -z $dns_ip ]]; then
  die "$DOMAIN does not resolve yet. Create an A record $DOMAIN -> ${public_ip:-<server IP>}, wait a few minutes, run again."
elif [[ -n $public_ip && $dns_ip != "$public_ip" ]]; then
  if curl -fsS -m 10 "http://$DOMAIN/cdn-cgi/trace" 2>/dev/null | grep -q "^fl="; then
    die "$DOMAIN goes through the Cloudflare proxy (orange cloud). In Cloudflare DNS set this record to 'DNS only' (grey cloud), wait a minute, run again. (The proxy hides real client IPs from the login rate limit and breaks the Telegram webhook filter.)"
  fi
  die "$DOMAIN points to $dns_ip but this server is $public_ip. Fix the A record and run again."
fi
ok "DNS OK ($DOMAIN -> $dns_ip)"

say "4/8 Building the application (several minutes the first time)"
docker compose build

say "5/8 SSL certificate"
if [[ -s /etc/letsencrypt/live/$DOMAIN/fullchain.pem ]]; then
  ok "certificate already present"
else
  docker compose stop nginx >/dev/null 2>&1 || true
  DOMAIN=$DOMAIN LE_EMAIL=$LE_EMAIL APP_DIR=$APP_DIR bash infra/scripts/init-ssl.sh
fi

say "6/8 Starting services"
docker compose up -d --wait db migrate api web nginx
code=$(curl -s -o /dev/null -w '%{http_code}' "https://$DOMAIN/api/health/ready" || true)
[[ $code == 200 ]] && ok "https://$DOMAIN is up" || die "health check failed ($code): docker compose logs api nginx"

say "7/8 Coach account"
if docker compose exec -T db psql -U basharnia -d basharnia -Atc "SELECT count(*) FROM users" | grep -qx 0; then
  if [[ -n ${PANEL_USER:-} ]]; then
    # Unattended: random temporary password, readable only by root. Change it after the first login.
    pw_file=/root/basharnia-panel-password.txt
    (umask 077; printf 'username: %s\npassword: %s\n' "$PANEL_USER" "$(rand 16)" > "$pw_file")
    ADMIN_USERNAME=$PANEL_USER INITIAL_ADMIN_PASSWORD=$(awk '/^password:/{print $2}' "$pw_file") \
      docker compose run --rm -T -e ADMIN_USERNAME -e INITIAL_ADMIN_PASSWORD api python -m app.cli create-admin
    ok "account '$PANEL_USER' created; its temporary password is in $pw_file (root only)"
  else
    echo "Choose the coach's username and password (at least 10 characters):"
    docker compose run --rm api python -m app.cli create-admin
  fi
else
  ok "account already exists (forgot the password? docker compose run --rm api python -m app.cli reset-password)"
fi

say "8/8 Whisper model and Telegram"
docker compose run --rm worker python -m app.cli download-whisper-model
docker compose up -d worker
docker compose run --rm api python -m app.cli set-webhook
docker compose run --rm api python -m app.cli webhook-info

cat <<DONE

==========================================================
 Installed:  https://$DOMAIN
 - Log in with the account you just created.
 - In Telegram, send /start to the bot.
 - Next: set up backups (docs/DEPLOYMENT.md, section 8).
 - Log in from now on as: ssh $ADMIN_USER@$DOMAIN
==========================================================
DONE
